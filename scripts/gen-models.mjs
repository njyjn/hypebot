// Regenerates the model dropdown from Apple SG's buy pages.
// Run: npm run gen:models   (builds first, then rewrites
// src/sources/apple-sg-models.ts and the `models` list in config.yaml)
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { fetchText } from "../dist/http.js";
import { parseCatalogue } from "../dist/sources/apple-sg.js";

const PRODUCTS = ["iphone-duo"];
const CAPACITY_ORDER = ["64gb", "128gb", "256gb", "512gb", "1tb", "2tb"];
const root = (p) => fileURLToPath(new URL(`../${p}`, import.meta.url));

const models = {};
for (const product of PRODUCTS) {
  const page = await fetchText(`https://www.apple.com/sg/shop/buy-iphone/${product}`);
  const cat = parseCatalogue(page.body);
  if (page.status !== 200 || cat.entries.length === 0) throw new Error(`No models read for ${product} (HTTP ${page.status})`);
  const entries = [...cat.entries].sort(
    (a, b) => a.colourName.localeCompare(b.colourName) || CAPACITY_ORDER.indexOf(a.capacity) - CAPACITY_ORDER.indexOf(b.capacity),
  );
  for (const e of entries) {
    const variant = `${e.colourName} / ${e.capacity.toUpperCase()}`;
    models[`${cat.productName} / ${variant}`] = { product, variant };
  }
}

const labels = Object.keys(models);
if (labels.some((l) => l.includes("|") || l.includes(")"))) throw new Error("A label contains | or ), which the add-on schema cannot hold");

writeFileSync(
  root("src/sources/apple-sg-models.ts"),
  `// Generated by scripts/gen-models.mjs from Apple SG's buy pages. Do not edit by hand.
// These are the choices in the add-on's \`models\` dropdown.
export const APPLE_SG_MODELS: Record<string, { product: string; variant: string }> = ${JSON.stringify(models, null, 2)};
`,
);

const configPath = root("config.yaml");
const config = readFileSync(configPath, "utf8");
const pattern = /(\n  models:\n    - ")list\([^\n]*\)\?"/;
if (!pattern.test(config)) throw new Error("config.yaml has no `models:` schema line to update");
writeFileSync(configPath, config.replace(pattern, `$1list(${labels.join("|")})?"`));

console.log(`Wrote ${labels.length} models:\n${labels.join("\n")}`);
